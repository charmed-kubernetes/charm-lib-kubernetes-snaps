"""The current code writes the same bytes and builds the same argument strings as
the published 0.0.1 wheel, so the first upgrade does not restart services.

The fixture was captured from the wheel by `capture_golden.py`, not generated by the
code under test.
"""

import json
from pathlib import Path

import golden_scenario
import yaml

from charms import kubernetes_snaps

GOLDEN = Path(__file__).parent / "golden_0_0_1.json"


def test_output_matches_published_0_0_1(tmp_path):
    golden = json.loads(GOLDEN.read_text())
    result = golden_scenario.run(kubernetes_snaps, tmp_path)

    assert [s["name"] for s in result["steps"]] == [s["name"] for s in golden["steps"]]
    note = (
        f"fixture captured with PyYAML {golden['pyyaml']}, running {yaml.__version__}"
    )
    for expected, actual in zip(golden["steps"], result["steps"]):
        assert actual == expected, f"{expected['name']}: {note}"
